from pydantic import BaseModel, Field
from enum import StrEnum
from typing import TypedDict, Any

class AgentName(StrEnum):
    """Components that can contribute to the initial investigation loop."""

    COORDINATOR = "coordinator"
    GRAPH_INVESTIGATOR = "graph_investigator"
    RISK_ANALYST = "risk_analyst"

class RiskAssessment(StrEnum):
    """Possible assessment or verdict of a candidate exposure path."""

    CONFIRMED = "confirmed"
    REJECTED = "rejected"
    NEEDS_MORE_EVIDENCE = "needs_more_evidence"

class NextAction(StrEnum):
    """Routing decisions available to the Coordinator."""

    INVESTIGATE_GRAPH = "investigate_graph"
    ANALYZE_RISK = "analyze_risk"
    FINALIZE = "finalize"

class InvestigationStatus(StrEnum):
    """Progress and termination states for an investigation."""

    IN_PROGRESS = "in_progress"
    COMPLETED = "completed"
    INSUFFICIENT_EVIDENCE = "insufficient_evidence"
    LIMIT_REACHED = "limit_reached"

class AgentRequest(BaseModel):
    """A focused request from the Coordinator to another agent."""

    target_agent: AgentName = Field(
        description="Specialist agent that should handle this request."
    )
    objective: str = Field(
        min_length=1,
        description=(
            "Focused task for the specialist. Request evidence or analysis "
            "without assuming the conclusion."
        ),
    )
    entity_references: list[str] = Field(
        default_factory=list,
        description=(
            "Relevant entity names or canonical graph IDs. Names may be "
            "unresolved and must be resolved by the Graph Investigator."
        ),
    )

class CoordinatorDecision(BaseModel):
    """A validated routing decision produced by the Coordinator."""

    investigation_goal: str = Field(
        min_length=1,
        description=(
            "Normalized investigation goal that preserves the user's "
            "certainty and security terminology."
        ),
    )
    next_action: NextAction = Field(
        description="Next investigation action selected from the current state."
    )
    reasoning: str = Field(
        min_length=1,
        description=(
            "Brief state-grounded justification for the routing decision, "
            "not detailed chain-of-thought."
        ),
    )
    agent_request: AgentRequest | None = Field(
        default=None,
        description="Focused specialist request; omitted only when finalizing.",
    )

class RiskFinding(BaseModel):
    """The Risk Agent's assessment of a candidate path."""

    path_id: str = Field(min_length=1)
    assessment: RiskAssessment
    explanation: str = Field(min_length=1)
    missing_evidence: list[str] = Field(
        default_factory=list,
        description=(
            "Each item is one complete evidence-gap question naming the "
            "relevant source entity, target entity, and missing fact. Entity "
            "names must not be returned as separate list items."
        ),
    )

class RiskAnalysisResult(BaseModel):
    """Structured assessment returned by the Risk Agent."""

    findings: list[RiskFinding] = Field(
        default_factory=list,
        description="Risk assessment for each candidate path that was reviewed.",
    )
    evidence_sufficient: bool = Field(
        description="Whether the available evidence can answer the investigation goal.",
    )
    open_questions: list[str] = Field(
        default_factory=list,
        description="Questions that identify evidence still needed.",
    )
    summary: str = Field(
        min_length=1,
        description="Brief evidence-based risk summary.",
    )

class PathAssessment(BaseModel):
    assessment: RiskAssessment
    explanation: str = Field(
        min_length=1, # Because, we do not want the explanation generated by LLM to be empty
        description="Explain why the path received this assessment, using only the supplied graph evidence."
    )
    missing_evidence: list[str] = Field(
        default_factory=list, #missing_evidence will be empty list [] when LLM skips this field in output
        description="Full questions asking for the missing evidence needed to assess the path."
    )

class AgentName(StrEnum):
    """Components/specialist agents that can contribute to the initial investigation loop."""

    COORDINATOR = "coordinator"
    GRAPH_INVESTIGATOR = "graph_investigator"
    RISK_ANALYST = "risk_analyst"

class AgentRequest(BaseModel):
    """A focused request from the Coordinator to another agent."""

    target_agent: AgentName = Field(
        description="Specialist agent that should handle this request."
    )
    objective: str = Field(
        min_length=1,
        description=(
            "Focused task for the specialist. Request evidence or analysis "
            "without assuming the conclusion."
        ),
    )
    entity_references: list[str] = Field(
        default_factory=list,
        description=(
            "Entity names or exact graph IDs. The Graph Investigator looks up names to find matching graph nodes and their IDs."
        )
    )

class EvidenceRecord(BaseModel):
    """A unit of evidence returned by a controlled graph operation."""

    evidence_id: str = Field(min_length=1)
    source_operation: str = Field(
        min_length=1,
        description="Name of the graph query operation that produced this evidence.",
    )
    content: dict[str, Any] = Field(
        min_length=1,
        description="The query inputs and graph results recorded as evidence.",
    )

class CandidatePath(BaseModel):
    """An evidence-backed path awaiting risk assessment."""

    path_id: str = Field(min_length=1)
    node_ids: list[str] = Field(min_length=2)
    relationship_ids: list[str] = Field(min_length=1)
    critical_asset_id: str = Field(min_length=1)

class InvestigationEvent(BaseModel):
    """A compact history entry for one investigation action."""

    round_number: int = Field(ge=0)
    agent: AgentName
    outcome: str = Field(min_length=1)
    evidence_ids: list[str] = Field(default_factory=list)

class InvestigationState(TypedDict):
    """LangGraph-compatible shared state for the initial investigation loop."""

    user_query: str
    investigation_goal: str
    evidence: list[EvidenceRecord]
    candidate_paths: list[CandidatePath]
    risk_findings: list[RiskFinding]
    risk_evidence_sufficient: bool | None # Latest Risk Analyst verdict; None means the current evidence has not been assessed.
    open_questions: list[str]
    next_action: NextAction | None
    agent_request: AgentRequest | None
    history: list[InvestigationEvent]
    round_count: int
    max_rounds: int
    no_progress: bool
    status: InvestigationStatus
    final_summary: str | None

class GraphInvestigationResult(BaseModel):
    """Structured facts returned by the Graph Investigator."""

    evidence: list[EvidenceRecord] = Field(
        default_factory=list,
        description="Facts retrieved through controlled Neo4j operations.",
    )
    candidate_paths: list[CandidatePath] = Field(
        default_factory=list,
        description="Evidence-backed paths that still require risk assessment.",
    )
    discovered_entity_ids: list[str] = Field(
        default_factory=list,
        description="Canonical IDs of relevant entities found during retrieval.",
    )
    unresolved_entity_references: list[str] = Field(
        default_factory=list,
        description="Requested entity names or IDs that could not be resolved.",
    )
    open_questions: list[str] = Field(
        default_factory=list,
        description="Evidence gaps that may require another investigation step.",
    )
    summary: str = Field(
        min_length=1,
        description="Brief factual summary without a risk conclusion.",
    )

class GraphOperation(StrEnum):
    """Read-only graph searches the investigator may request."""

    FIND_PATHS = "find_paths_to_critical_assets"
    EXPAND_NEIGHBORHOOD = "expand_neighborhood"
    GET_PERMISSIONS = "get_permissions"
    GET_ASSET_PERMISSIONS = "get_asset_permissions"
    GET_VULNERABILITIES = "get_vulnerabilities"

class GraphQueryCall(BaseModel):
    """One approved graph search and the resolved entity it should inspect."""

    operation: GraphOperation = Field(description="Approved read-only graph search.")
    entity_id: str = Field(
        min_length=1,
        description="Exact ID of an entity supplied in the resolved entities.",
    )


class GraphQueryPlan(BaseModel):
    """The investigator's short list of graph searches for this request."""

    calls: list[GraphQueryCall] = Field(description="One to three different searches needed for the objective.")
